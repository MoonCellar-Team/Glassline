ResourceManager::ResourceManager() : m_unk00(false) {}

ResourceManager::~ResourceManager() {}

midp::InputStream* ResourceManager::loadBinaryFile(int id) {
    return midp::Class::getResourceAsStream(new midp::String(RESOURCE_FILENAMES_LIST[id]));
}

midp::array<m3g::Object3D*> ResourceManager::loadM3GFile(int id) {
    return m3g::Loader::load(loadBinaryFile(id));
}

m3g::Image2D* ResourceManager::loadM3GImage2D(int id) {
    m3g::Image2D* image = NULL;
    midp::array<m3g::Object3D*> objects = loadM3GFile(id);
    if (m3g::m3g_cast<m3g::Image2D>(objects[0]) != NULL) {
        image = static_cast<m3g::Image2D*>(objects[0]);
    }
    midp::INCREF(image);
    int i = objects.m_length;
    while (i != 0) {
        i--;
        midp::DECREF(objects[i]);
    }
    return image;
}

m3g::Object3D* ResourceManager::loadM3GNode(int id) {
    m3g::Object3D* node = NULL;
    midp::array<m3g::Object3D*> objects = loadM3GFile(id);
    if (objects != NULL) {
        node = objects[0];
    }
    midp::INCREF(node);
    for (int i = objects.m_length - 1; i >= 0; i--) {
        midp::DECREF(objects[i]);
    }
    return node;
}

midp::Image* ResourceManager::loadImage(int id) const {
    return midp::Image::createImage(loadBinaryFile(id));
}

